package io.demo.service.rag;

import java.util.List;

/**
 * Mirrors the {@code kbee.rag.search.SummariesResponse} record returned by the
 * Kbee RAG Server ({@code /api/rag/summaries}).
 * <p>
 * The server response does not carry the {@code llm} used to generate the
 * summaries (see {@code kbee.rag.search.SummariesResponse}); {@link #llm()}
 * is filled in by {@link KbeeRAGClient#getSummaries(String)} with the value
 * sent in the request, so callers always have it available.
 * </p>
 */
public record SummariesResponse(
        String documentId,
        List<Summary> summaries,
        String llm) {

    /**
     * A single summary generated by the RAG server. Mirrors
     * {@code kbee.rag.judicial.SummaryPrint} (title, text, terms).
     */
    public record Summary(String title, String text, List<String> terms) {
    }
}
